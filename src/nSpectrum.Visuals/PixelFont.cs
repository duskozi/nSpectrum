namespace nSpectrum.Visuals;

/// <summary>An original 5×7 pixel font: ASCII 32..126 plus a few symbols (·, °, µ). Unknown characters draw as a box.</summary>
internal static class PixelFont
{
    private const int First = 32, Last = 126;
    private const int Extra = Last - First + 1; // index of the first extra glyph

    public static ReadOnlySpan<byte> Glyph(char c)
    {
        int index = c switch
        {
            >= (char)First and <= (char)Last => c - First,
            '·' => Extra,
            '°' => Extra + 1,
            'µ' => Extra + 2,
            '−' => '-' - First,
            _ => Extra + 3,
        };
        return Table.AsSpan(index * 7, 7);
    }

    // Each glyph: 7 rows of 5 columns, '#' = on.
    private static readonly string[] Source =
    [
        "     |     |     |     |     |     |     ", // space
        "  #  |  #  |  #  |  #  |  #  |     |  #  ", // !
