        "#####|#   #|#   #|#   #|#   #|#   #|#####", // box
    ];

    // Declared after Source: static initialisers run in text order.
    private static readonly byte[] Table = Build();

    private static byte[] Build()
    {
        var t = new byte[Source.Length * 7];
        for (int g = 0; g < Source.Length; g++)
        {
            string[] rows = Source[g].Split('|');
            if (rows.Length != 7) throw new InvalidOperationException($"Glyph {g} has {rows.Length} rows.");
            for (int r = 0; r < 7; r++)
            {
                byte bits = 0;
                for (int c = 0; c < 5; c++)
                    if (c < rows[r].Length && rows[r][c] == '#') bits |= (byte)(0x10 >> c);
                t[g * 7 + r] = bits;
            }
        }
        return t;
    }
}
